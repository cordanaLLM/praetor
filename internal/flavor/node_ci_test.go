package flavor_test

// The scaffolded Node CI job must pass as written wherever flavor apply writes it. Adoption
// makes every job of a scaffolded workflow a required status check, and typescript-node
// detects any package.json: a Go repository carrying a package.json for its commit tooling used
// to receive `npm ci` + `npm test` as a check no pull request could pass, and a pnpm, Yarn or Bun
// project got no job at all (BUG-1011). The job runs on CI's checkout, not the working tree, so
// a lockfile Git never commits counts as no lockfile.

