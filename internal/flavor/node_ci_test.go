// The scaffolded job is written only where each of its steps can pass, and every step of the
// body it writes is checked against the fixture: every tool, lockfile and script it names exists.
func TestNodeCIJobIsScaffoldedOnlyWhereItRunsAsWritten(t *testing.T) {
	for _, tc := range nodeCICases() {
		t.Run(tc.name, func(t *testing.T) {
			repo := tc.repo(t)
			if tc.flavor == "auto" {
				if got, _ := resolve(repo); got != "typescript-node" {
					t.Fatalf("fixture detects %q, not typescript-node; the case no longer tests the job", got)
				}
			}
			report, err := flavor.ApplyFlavor(t.Context(), repo, tc.flavor, false)
			if err != nil || len(report.Errors) > 0 {
				t.Fatalf("apply: err %v, recorded %v", err, report.Errors)
			}
			data, readErr := os.ReadFile(filepath.Join(repo, nodeCIPath))
			if written := readErr == nil; written != (tc.unmet == "") {
				t.Fatalf("CI job scaffolded = %v, want %v; report %+v", written, tc.unmet == "", report)
			}
			if tc.unmet != "" {
				assertUnmet(t, report, tc.unmet)
				return
			}
			if problems := unrunnableNodeSteps(t, string(data), repo); len(problems) > 0 {
				t.Fatalf("the scaffolded job cannot pass here: %v\n%s", problems, data)
			}
			assertJobRuns(t, string(data), tc.runs, tc.absent)
		})
	}
}

// assertJobRuns checks the job runs every command in runs and none in absent.
func assertJobRuns(t *testing.T, body string, runs, absent []string) {
	t.Helper()
	var lines []string
	for _, run := range workflowRunSteps(t, body) {
		lines = append(lines, strings.Split(strings.TrimSpace(run), "\n")...)
	}
	for _, want := range runs {
		if !slices.Contains(lines, want) {
			t.Errorf("the job does not run %q:\n%s", want, body)
		}
	}
	for _, unwanted := range absent {
		if slices.Contains(lines, unwanted) {
			t.Errorf("the job runs %q:\n%s", unwanted, body)
		}
	}
}

func assertUnmet(t *testing.T, report *flavor.ApplyReport, fragment string) {
	t.Helper()
	for _, entry := range report.UnmetTemplates {
		if strings.HasPrefix(entry, nodeCIPath+": ") && strings.Contains(entry, fragment) {
			return
		}
	}
	t.Fatalf("want %s reported unmet with %q, got %v", nodeCIPath, fragment, report.UnmetTemplates)
}

// namedNodeCICase returns the named case.
func namedNodeCICase(t *testing.T, name string) nodeCICase {
	t.Helper()
	cases := nodeCICases()
	i := slices.IndexFunc(cases, func(tc nodeCICase) bool { return tc.name == name })
	if i < 0 {
		t.Fatalf("no case named %s", name)
	}
	return cases[i]
}

// The check above is only as good as its ability to fail. Replayed against each manager's job
// as the template renders it, it flags every repository that job cannot pass in, including the
// npm job in a pnpm project (the body flavor apply once wrote there) and a Yarn 1 install in a
// Yarn 4 project, and passes the repository the job is for.
func TestUnrunnableNodeStepsCatchesTheJobWhereItCannotPass(t *testing.T) {
	for _, check := range []struct {
		node   templates.NodeContext
		passes string
		fails  []string
	}{
		{templates.NodeContext{}, "npm-project", []string{"pnpm-lock-only", "npm-init-placeholder", "shrinkwrap-only", "ignored-lockfile", "yarn-declared-npm-lock"}},
		{templates.NodeContext{Manager: "pnpm"}, "pnpm-lock-only", []string{"npm-project", "yarn-classic-lock-only", "yarn-declared-npm-lock"}},
		{templates.NodeContext{Manager: "yarn", Lint: true}, "yarn-classic-lock-only", []string{"yarn-berry-declared", "yarn-berry-yarnpath", "pnpm-lock-only"}},
		{templates.NodeContext{Manager: "yarn", YarnBerry: true}, "yarn-berry-declared", []string{"yarn-classic-lock-only", "npm-project"}},
		{templates.NodeContext{Manager: "bun"}, "bun-lock", []string{"npm-project", "pnpm-declared", "npm-init-placeholder"}},
	} {
		body, err := templates.RenderFile("node/ci-node.yml.tmpl", templates.Context{RepoName: "widget", Owner: "acme", Node: check.node})
		if err != nil {
			t.Fatalf("render %+v: %v", check.node, err)
		}
		for _, name := range check.fails {
			if problems := unrunnableNodeSteps(t, body, namedNodeCICase(t, name).repo(t)); len(problems) == 0 {
				t.Errorf("%+v in %s: the check passed a job that fails there", check.node, name)
			}
		}
		if problems := unrunnableNodeSteps(t, body, namedNodeCICase(t, check.passes).repo(t)); len(problems) > 0 {
			t.Errorf("%+v in %s: the check rejected a job that passes: %v", check.node, check.passes, problems)
		}
	}
	// Boundary: a command the check does not model is a finding, not a pass, and so is a Yarn
	// --if-present, which Yarn does not have.
	repo := namedNodeCICase(t, "yarn-classic-lock-only").repo(t)
	for _, run := range []string{"deno task test", "yarn run --if-present lint"} {
		unknown := "jobs:\n  test:\n    steps:\n      - uses: actions/setup-node@v4\n      - run: npm install --global corepack@latest\n      - run: corepack enable yarn\n      - run: " + run + "\n"
		if problems := unrunnableNodeSteps(t, unknown, repo); len(problems) != 1 {
			t.Errorf("%q: want one finding, got %v", run, problems)
		}
	}
}

// Boundary: --force replaces existing files, never with a job that cannot pass. An existing
// workflow in a pnpm project whose lockfile is missing stays exactly as it was.
func TestApplyFlavor_Boundary_ForceNeverWritesAnUnrunnableNodeJob(t *testing.T) {
	own := "name: CI\non: push\njobs:\n  test:\n    runs-on: ubuntu-26.04\n    steps:\n      - run: pnpm test\n"
	files := map[string]string{"package.json": `{"packageManager": "pnpm@10.0.0", "scripts": {"test": "vitest"}}`, "package-lock.json": npmLock, nodeCIPath: own}
	repo := gitRepoWithFiles(t, files)
	report, err := flavor.ApplyFlavor(t.Context(), repo, "typescript-node", true)
	if err != nil || len(report.Errors) > 0 {
		t.Fatalf("apply --force: err %v, recorded %v", err, report.Errors)
	}
	data, err := os.ReadFile(filepath.Join(repo, nodeCIPath))
	if err != nil || string(data) != own {
		t.Fatalf("--force replaced the repository's workflow: err %v\n%s", err, data)
	}
	assertUnmet(t, report, "no pnpm-lock.yaml")
}
