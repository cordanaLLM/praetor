const nodeCIPath = ".github/workflows/ci.yml"

// npmLock is a package-lock.json npm ci accepts for a package with no dependencies.
const npmLock = `{"name": "widget", "lockfileVersion": 3, "requires": true, "packages": {"": {"name": "widget"}}}` + "\n"

// Lockfile bodies for the other managers. The model below reads only their names.
const (
	pnpmLock   = "lockfileVersion: '9.0'\n"
	yarnV1Lock = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n"
	yarnV2Lock = "__metadata:\n  version: 8\n"
	bunLock    = "{\"lockfileVersion\": 1, \"workspaces\": {\"\": {\"name\": \"widget\"}}}\n"
)

// setupNodeLockfiles are the files setup-node's `cache: npm` looks for in the repository root;
// with none of them the action fails the job (actions/setup-node src/cache-utils.ts,
// findLockFile in src/cache-restore.ts).
var setupNodeLockfiles = []string{"package-lock.json", "npm-shrinkwrap.json", "yarn.lock"}

// lockedInstalls are the install commands the check models, each with the lockfiles it reads
// and, for Yarn, the major line whose flag it is: Yarn 2+ spells the locked install --immutable
// and Yarn 1 --frozen-lockfile. The table is this test's own, not nodemanifest's, so the two
// cannot share a mistake about which manager reads which lockfile.
var lockedInstalls = map[string]struct {
	lockfiles []string
	yarnBerry *bool
}{
	"npm ci":                         {lockfiles: []string{"package-lock.json"}},
	"pnpm install --frozen-lockfile": {lockfiles: []string{"pnpm-lock.yaml"}},
	"yarn install --frozen-lockfile": {lockfiles: []string{"yarn.lock"}, yarnBerry: new(false)},
	"yarn install --immutable":       {lockfiles: []string{"yarn.lock"}, yarnBerry: new(true)},
	"bun install --frozen-lockfile":  {lockfiles: []string{"bun.lock", "bun.lockb"}},
}

// nodeWorkflow is the part of a workflow the runnability check reads.
type nodeWorkflow struct {
	Jobs map[string]struct {
		Steps []struct {
			Uses string            `yaml:"uses"`
			With map[string]string `yaml:"with"`
			Run  string            `yaml:"run"`
		} `yaml:"steps"`
	} `yaml:"jobs"`
}

// nodeJob is what a Node CI job has installed so far, and the checkout it runs on.
type nodeJob struct {
	checkout map[string]bool
	scripts  map[string]string
	// declared is the manager packageManager names, "" for none; yarnBerry is whether the Yarn
	// Corepack runs there is 2 or later.
	declared  string
	yarnBerry bool
	tools     map[string]bool
}

// unrunnableNodeSteps returns every step of a Node workflow that cannot pass on CI's checkout of
// repo: an action whose inputs the checkout does not satisfy, a command naming a lockfile,
// script or tool that is not there, and any action or command the check does not model, so a
// later body cannot add one unchecked. The hosted gate's draft step is not read (draftSteps): it
// runs on a draft alone and fails it by design, so a ready pull request never runs it.
func unrunnableNodeSteps(t *testing.T, body, repo string) []string {
	t.Helper()
	var workflow nodeWorkflow
	if err := yaml.Unmarshal([]byte(body), &workflow); err != nil {
		t.Fatalf("parse workflow: %v\n%s", err, body)
	}
	spec, err := ghworkflow.Parse([]byte(body))
	if err != nil {
		t.Fatalf("parse workflow: %v\n%s", err, body)
	}
	var problems []string
	for id, steps := range workflow.Jobs {
		job := newNodeJob(t, repo)
		for i := draftSteps(spec.Jobs[id].Steps); i < len(steps.Steps) && i < maxWorkflowSteps; i++ {
			step := steps.Steps[i]
			if step.Uses != "" {
				problems = append(problems, job.action(step.Uses, step.With)...)
			}
			problems = append(problems, job.commands(step.Run)...)
		}
	}
	return problems
}

// draftSteps is how many leading steps of a job a ready pull request never runs: one when the
// first is the hosted gate's draft step (ghworkflow.DraftStepFault), none otherwise.
func draftSteps(steps []ghworkflow.Step) int {
	if len(steps) > 0 && ghworkflow.DraftStepFault(&steps[0]) == nil {
		return 1
	}
	return 0
}

func newNodeJob(t *testing.T, repo string) *nodeJob {
	t.Helper()
	manifest := readFixtureManifest(t, repo)
	declared, version, _ := strings.Cut(manifest.packageManager, "@")
	yarnrc, err := os.ReadFile(filepath.Join(repo, ".yarnrc.yml"))
	if err != nil && !os.IsNotExist(err) {
		t.Fatalf("read .yarnrc.yml: %v", err)
	}
	berry := strings.HasPrefix(string(yarnrc), "yarnPath:") || strings.Contains(string(yarnrc), "\nyarnPath:")
	if declared == "yarn" {
		major, _, _ := strings.Cut(version, ".")
		n, err := strconv.Atoi(major)
		berry = err == nil && n >= 2
	}
	return &nodeJob{checkout: checkoutFiles(t, repo), scripts: manifest.scripts, declared: declared, yarnBerry: berry, tools: map[string]bool{}}
}

// maxCheckoutFiles bounds the files read from one fixture's index (HISS-02).
const maxCheckoutFiles = 4096

// checkoutFiles returns the slash paths CI's checkout of repo would hold once its working tree
// is committed: what `git add -A` stages. Git leaves out an untracked file the repository's
// ignore rules exclude and keeps one already tracked, whatever the rules say. The model is
// Git's own staging, not the check-ignore query nodeCIRequirement makes, so the two cannot share
// a mistake about which files a checkout carries.
func checkoutFiles(t *testing.T, repo string) map[string]bool {
	t.Helper()
	runFixtureGit(t, repo, "add", "-A")
	names := strings.Split(string(runFixtureGit(t, repo, "ls-files", "-z")), "\x00")
	files := make(map[string]bool, len(names))
	for i := 0; i < len(names) && i < maxCheckoutFiles; i++ {
		if names[i] != "" {
			files[names[i]] = true
		}
	}
	return files
}

func (job *nodeJob) action(uses string, with map[string]string) []string {
	switch {
	case strings.HasPrefix(uses, "actions/checkout@"):
		return nil
	case strings.HasPrefix(uses, "actions/setup-node@"):
		job.tools["npm"] = true
		if with["cache"] == "npm" && !slices.ContainsFunc(setupNodeLockfiles, func(name string) bool { return job.checkout[name] }) {
			return []string{uses + ": cache: npm finds no lockfile"}
		}
		return nil
	case strings.HasPrefix(uses, "oven-sh/setup-bun@") && len(with) == 0:
		job.tools["bun"] = true
		return nil
	default:
		return []string{uses + ": action not modelled by this check"}
	}
}

// maxRunLines bounds the lines read from one run: body (HISS-02).
const maxRunLines = 64

func (job *nodeJob) commands(run string) []string {
	var problems []string
	lines := strings.Split(run, "\n")
	for i := 0; i < len(lines) && i < maxRunLines; i++ {
		fields := strings.Fields(lines[i])
		if len(fields) == 0 || strings.HasPrefix(fields[0], "#") {
			continue
		}
		if problem := job.command(fields); problem != "" {
			problems = append(problems, problem)
		}
	}
	return problems
}

// command checks one command line against what the job has installed. Corepack comes from npm,
// and `corepack enable <manager>` puts pnpm or Yarn on PATH; Corepack refuses a manager other
// than the one packageManager names.
func (job *nodeJob) command(fields []string) string {
	command := strings.Join(fields, " ")
	switch {
	case command == "npm install --global corepack@latest":
		return job.install("npm", "corepack", command)
	case command == "corepack enable pnpm" || command == "corepack enable yarn":
		return job.install("corepack", fields[2], command)
	case !slices.Contains([]string{"npm", "pnpm", "yarn", "bun"}, fields[0]):
		return command + ": command not modelled by this check"
	case !job.tools[fields[0]]:
		return command + ": no step installs " + fields[0]
	case job.declared != "" && job.declared != fields[0]:
		return command + ": package.json declares packageManager " + job.declared
	}
	return job.managerCommand(fields, command)
}

// install records tool as installed by a command that needs by.
func (job *nodeJob) install(by, tool, command string) string {
	if !job.tools[by] {
		return command + ": no step installs " + by
	}
	job.tools[tool] = true
	return ""
}

// managerCommand checks a package manager's own command: a locked install needs its lockfile in
// the checkout (and, for Yarn, the flag of the Yarn that runs), `npm test` and `<manager> run
// <name>` fail on a script that is missing or cannot pass, and --if-present, spelled where each
// manager reads it, makes an absent script a no-op. Yarn has no --if-present.
func (job *nodeJob) managerCommand(fields []string, command string) string {
	manager, args := fields[0], fields[1:]
	if install, ok := lockedInstalls[command]; ok {
		if !slices.ContainsFunc(install.lockfiles, func(name string) bool { return job.checkout[name] }) {
			return command + ": no " + strings.Join(install.lockfiles, " or ") + " in the checkout"
		}
		if install.yarnBerry != nil && *install.yarnBerry != job.yarnBerry {
			return command + ": not the locked-install flag of the Yarn that runs here"
		}
		return ""
	}
	switch {
	case manager == "npm" && len(args) == 3 && args[0] == "run" && args[2] == "--if-present":
		return ""
	case (manager == "pnpm" || manager == "bun") && len(args) == 3 && args[0] == "run" && args[1] == "--if-present":
		return ""
	case manager == "npm" && command == "npm test":
		return job.script("test", command)
	case len(args) == 2 && args[0] == "run" && !strings.HasPrefix(args[1], "-"):
		return job.script(args[1], command)
	}
	return command + ": command not modelled by this check"
}

func (job *nodeJob) script(name, command string) string {
	if !nodemanifest.ScriptRuns(job.scripts[name]) {
		return command + ": no " + name + " script that can pass"
	}
	return ""
}

// fixtureManifest is what the check reads from a fixture's package.json.
type fixtureManifest struct {
	packageManager string
	scripts        map[string]string
}

func readFixtureManifest(t *testing.T, repo string) fixtureManifest {
	t.Helper()
	var manifest fixtureManifest
	data, err := os.ReadFile(filepath.Join(repo, "package.json"))
	if os.IsNotExist(err) {
		return manifest
	}
	if err != nil {
		t.Fatalf("read package.json: %v", err)
	}
	// Exact keys, as npm reads them: a tagged struct field would also take "Scripts".
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		t.Fatalf("parse package.json: %v", err)
	}
	if raw, ok := fields["scripts"]; ok {
		if err := json.Unmarshal(raw, &manifest.scripts); err != nil {
			t.Fatalf("parse package.json scripts: %v", err)
		}
	}
	if raw, ok := fields["packageManager"]; ok {
		if err := json.Unmarshal(raw, &manifest.packageManager); err != nil {
			t.Fatalf("parse package.json packageManager: %v", err)
		}
	}
	return manifest
}

// nodeCICase is one repository shape and whether flavor apply may scaffold the Node CI job there.
type nodeCICase struct {
	name  string
	files map[string]string
	// track lists files Git tracks, force-added past any ignore rule; noGit leaves the fixture
	// outside a Git work tree.
	track []string
	noGit bool
	// flavor is what apply is asked for; "auto" exercises Resolve as adoption does.
	flavor string
	// runs are commands the scaffolded job must run; absent are commands it must not.
	runs   []string
	absent []string
	// unmet is a fragment of the reason the job was not scaffolded; "" means it was.
	unmet string
}

// repo builds the case's fixture.
func (tc nodeCICase) repo(t *testing.T) string {
	t.Helper()
	if tc.noGit {
		return repoWithFiles(t, tc.files)
	}
	repo := gitRepoWithFiles(t, tc.files)
	if len(tc.track) > 0 {
		runFixtureGit(t, repo, append([]string{"add", "-f", "--"}, tc.track...)...)
	}
	return repo
}

