package gating

import (
	"context"
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestGeneratedGosecFindingExcluded plants a generated source finding at the scanner boundary.
func TestGeneratedGosecFindingExcluded(t *testing.T) {
	dir := t.TempDir()
	source := "// Code generated by test; DO NOT EDIT.\npackage sample\nimport \"crypto/md5\"\nvar _ = md5.New\n"
	if err := os.WriteFile(filepath.Join(dir, "generated.go"), []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	cfg, _ := newTestConfig(t, dir, false)
	cfg.run = func(_ context.Context, dir, _ string, args ...string) (string, error) {
		data, err := os.ReadFile(filepath.Join(dir, "generated.go"))
		if err != nil {
			return "", err
		}
		if strings.Contains(string(data), "crypto/md5") && !strings.Contains(strings.Join(args, " "), "-exclude-generated") {
			return "generated finding", errors.New("finding")
		}
		return "", nil
	}
	if _, err := runGosecScan(context.Background(), cfg, dir, ".gosec.json", []string{"."}); err != nil {
		t.Fatalf("generated finding should be excluded: %v", err)
	}
}
