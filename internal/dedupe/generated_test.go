const generatedCloneAlpha = `// Code generated by test-gen. DO NOT EDIT.
package sample

import "fmt"

func ProcessData(items []string) int {
	fmt.Println("step 1: process items")
	fmt.Println("step 2: calculate total")
	fmt.Println("step 3: finish execution")
	return len(items)
}
`

const generatedCloneBeta = `// Code generated by other-gen. DO NOT EDIT.
package sample

import "fmt"

func ProcessData(items []string) int {
	fmt.Println("step 1: process items")
	fmt.Println("step 2: calculate total")
	fmt.Println("step 3: finish execution")
	return len(items)
}
`

const handWrittenCloneA = `package sample

import "fmt"

func HandleRequest(msg string) string {
	fmt.Println("handling incoming request")
	fmt.Println("validating message payload")
	fmt.Println("dispatching to subsystem")
	return msg + ":ok"
}
`

const handWrittenCloneB = `package sample

import "fmt"

func HandleRequest(msg string) string {
	fmt.Println("handling incoming request")
	fmt.Println("validating message payload")
	fmt.Println("dispatching to subsystem")
	return msg + ":ok"
}
`

func TestScanRepo_Positive_GeneratedFilesAreSkipped(t *testing.T) {
	tmp := t.TempDir()
	if err := os.WriteFile(filepath.Join(tmp, "gen_a.go"), []byte(generatedCloneAlpha), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tmp, "gen_b.go"), []byte(generatedCloneBeta), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tmp, "hand_a.go"), []byte(handWrittenCloneA), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tmp, "hand_b.go"), []byte(handWrittenCloneB), 0o600); err != nil {
		t.Fatal(err)
	}

	report, err := dedupe.ScanRepo(tmp)
	if err != nil {
		t.Fatalf("scan repo failed: %v", err)
	}

	if report.SkippedGeneratedFiles != 2 {
		t.Errorf("SkippedGeneratedFiles = %d, want 2", report.SkippedGeneratedFiles)
	}
	if report.TotalFilesScanned != 2 {
		t.Errorf("TotalFilesScanned = %d, want 2", report.TotalFilesScanned)
	}
	if len(report.Duplicates) != 1 {
		t.Fatalf("Duplicates count = %d, want 1", len(report.Duplicates))
	}
	for _, loc := range report.Duplicates[0].Locations {
		if !strings.HasPrefix(loc.Path, "hand_") {
			t.Errorf("duplicate location = %q, want hand-written file", loc.Path)
		}
	}
}

