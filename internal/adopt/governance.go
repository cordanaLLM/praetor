// buildMakefile renders the greenfield Makefile. verify-all runs the same gates the
// AGENTS.md harness advertises; the test and build recipes follow detected project markers.
func buildMakefile(plan *VerificationPlan) string {
	return buildMakefileWithSourceGate(plan, verificationRecipePrefix, true)
}

// buildMakefileWith renders the greenfield Makefile with command lines starting with prefix.
func buildMakefileWith(plan *VerificationPlan, prefix string) string {
	return buildMakefileWithSourceGate(plan, prefix, true)
}

func buildMakefileWithSourceGate(plan *VerificationPlan, prefix string, sourceGate bool) string {
	gateTarget, gateRecipe, gatePhony := "", "", ""
	if sourceGate {
		gateTarget = " caveman-sources"
		gateRecipe = "caveman-sources:\n" + util.MakefileCLI("caveman check --configured-sources") + "\n"
		gatePhony = " caveman-sources"
	}
	return "# Generated by Praetor from declared project commands; execution is unverified.\n" +
		util.MakefileCLIVariable +
		".PHONY: all verify-all compile-context compile-context-verify" + gatePhony + " audit build test\n\n" +
		"all: build\n\n" +
		"verify-all: compile-context-verify" + gateTarget + " audit test\n\n" +
		"compile-context:\n" + util.MakefileCLI("compile-context") + "\n" +
		"compile-context-verify:\n" + util.MakefileCLI("compile-context --verify") + "\n" +
		gateRecipe +
		"audit:\n" + util.MakefileCLI("audit") + "\n" +
		"test: build\n" + verificationRecipeWith(plan, plan.Test, prefix) + "\n" +
		"build:\n" + verificationRecipeWith(plan, plan.Build, prefix)
}

func priorSourceGateMakefile(plan *VerificationPlan) string {
	return buildMakefileWithSourceGate(plan, verificationRecipePrefix, false)
}

func reconcileMakefile(ctx context.Context, s *adoptSession) error {
	documentationEnabled, err := documentationEnabledForSession(s)
	if err != nil {
		return fmt.Errorf("resolve documentation facet for Makefile: %w", err)
	}
	full, err := repoFile(s.repoPath, makefileName)
	if err != nil {
		return err
	}
	data, exists, err := contextopt.ObserveSnapshot(ctx, full)
	if err != nil {
		return err
	}
	data, err = reconcileDisabledDocumentationMakefile(ctx, s, full, data, exists, documentationEnabled)
	if err != nil {
		return err
	}
	generated := isReplaceableVerificationMakefile(string(data), s.verification)
	handled, err := reconcileExistingVerificationMakefile(ctx, s, string(data), exists, generated, documentationEnabled)
	if err != nil || handled {
		return err
	}
	replacement, err := verificationMakefileReplacement(s, string(data), exists, generated, documentationEnabled)
	if err != nil {
		return err
	}
	return publishVerificationMakefile(ctx, s, full, data, replacement, exists)
}

func reconcileDisabledDocumentationMakefile(
	ctx context.Context, s *adoptSession, full string, data []byte, exists, documentationEnabled bool,
) ([]byte, error) {
	if documentationEnabled || !exists {
		return data, nil
	}
	cleaned, removed, err := removeDocumentationMakefileBlock(string(data))
	if err != nil || !removed {
		return data, err
	}
	if !s.opts.DryRun {
		if err := contextopt.ReplaceSnapshot(ctx, full, []byte(cleaned), contextopt.ReplaceOptions{
			Expected: data, Exists: true, Mode: filePerm,
		}); err != nil {
			return nil, err
		}
	}
	s.report.recordReconciledAs(makefileName, actionRemove,
		"Removed canonical documentation gate because docs:seo-portal is disabled")
	return []byte(cleaned), nil
}

func publishVerificationMakefile(
	ctx context.Context, s *adoptSession, full string, data []byte, replacement string, exists bool,
) error {
	if !s.opts.DryRun {
		if err := contextopt.ReplaceSnapshot(ctx, full, []byte(replacement), contextopt.ReplaceOptions{
			Expected: data, Exists: exists, Mode: filePerm,
		}); err != nil {
			return err
		}
	}
	if exists {
		s.report.recordReconciledAs(makefileName, actionAppend, "Reconciled declared verification commands; preserved custom recipes")
	} else {
		s.report.recordCreated(makefileName, "Created Makefile from declared project verification commands")
	}
	return nil
}

func verificationMakefileReplacement(
	s *adoptSession, data string, exists, generated, documentationEnabled bool,
) (string, error) {
	replacement := buildMakefile(s.verification)
	if exists && !generated {
		var err error
		replacement, err = appendVerificationTargets(data, s.verification)
		if err != nil {
			return "", err
		}
	}
	if documentationEnabled {
		return mergeDocumentationMakefile(replacement, false)
	}
	return replacement, nil
}

func reconcileExistingVerificationMakefile(
	ctx context.Context, s *adoptSession, data string, exists, generated, documentationEnabled bool,
) (bool, error) {
	if !exists || !mayDefineVerificationTarget(data) || generated {
		return false, nil
	}
	if documentationEnabled {
		return true, reconcileDocumentationMakefile(ctx, s)
	}
	s.report.recordReconciled(makefileName, "Existing verify-all preserved; execution has not been verified by adoption")
	return true, nil
}

func reconcileContributing(ctx context.Context, s *adoptSession) error {
	_, err := s.scaffoldFile(ctx, scaffold{
		rel:      contributingFile,
		perm:     filePerm,
		content:  []byte(buildContributingGuide(s.repoName)),
		created:  "Scaffolded contributor governance guide with HISS & NASA rules",
		verified: "Existing contributor guide verified present",
	})
	return err
}

// reconcilePullRequestTemplate keeps whichever template name the repository already uses and
// compares it with the scaffold like every other preserved file.
func reconcilePullRequestTemplate(ctx context.Context, s *adoptSession) error {
	upper, err := repoFile(s.repoPath, prTemplateUpper)
	if err != nil {
		return err
	}
	rel := prTemplateFile
	if fileExists(upper) {
		rel = prTemplateUpper
	}
	_, err = s.scaffoldFile(ctx, scaffold{
		rel:      rel,
		perm:     filePerm,
		content:  []byte(buildPullRequestTemplate()),
		created:  "Scaffolded pull request template with HISS verification checklist",
		verified: "Existing pull request template verified present",
	})
	return err
}

