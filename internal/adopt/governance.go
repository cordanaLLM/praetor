func reconcileADR(_ context.Context, s *adoptSession) error {
	index, err := repoFile(s.repoPath, adrIndexFile)
	if err != nil {
		return err
	}
	if fileExists(index) {
		s.report.recordReconciled(adrIndexFile, "Architectural Decision Records directory verified present")
		return nil
	}
	tmpl, err := repoFile(s.repoPath, adrTemplateFile)
	if err != nil {
		return err
	}
	if err := s.write(index, []byte(buildADRIndex()), filePerm); err != nil {
		return err
	}
	if err := s.write(tmpl, []byte(buildADRTemplate()), filePerm); err != nil {
		return err
	}
	s.report.recordCreated(adrIndexFile, "Scaffolded Architectural Decision Records (ADR) directory and template")
	return nil
}

// reconcileReadme refreshes the only README region Praetor owns. A baseline records debt;
// it never certifies that the repository's full verification cascade passed.
func reconcileReadme(ctx context.Context, s *adoptSession) error {
	documentationEnabled, err := documentationEnabledForSession(s)
	if err != nil {
		return fmt.Errorf("resolve documentation facet for README: %w", err)
	}
	full, err := repoFile(s.repoPath, readmeFile)
	if err != nil {
		return err
	}
	data, exists, err := contextopt.ObserveSnapshot(ctx, full)
	if err != nil {
		return err
	}
	if !exists {
		return nil
	}
	state, err := readmeGovernanceState(s, documentationEnabled)
	if err != nil {
		return s.readmeStateError(err)
	}
	content, changed, err := readmegovernance.Reconcile(string(data), state)
	if err != nil || !changed {
		return err
	}
	if err := s.write(full, []byte(content), filePerm); err != nil {
		return err
	}
	s.report.recordReconciled(readmeFile, "Reconciled the marker-owned HISS adoption and verification contract")
	return nil
}

func readmeGovernanceState(s *adoptSession, documentationEnabled bool) (readmegovernance.State, error) {
	state := readmegovernance.State{
		BaselineKnown:        s.report.BaselineStatus == "scanned" || s.report.BaselineStatus == "existing",
		LegacyDebtCount:      s.report.LegacyDebtCount,
		DocumentationEnabled: documentationEnabled,
	}
	var manifest *config.Manifest
	if s.policy != nil {
		manifest = s.policy.Manifest
	}
	if documentationEnabled && manifest == nil {
		return state, fmt.Errorf("reconcile README documentation contract: effective manifest is unavailable")
	}
	owner, name, err := ReadmeIdentity(manifest, documentationEnabled)
	state.RepositoryOwner, state.RepositoryName = owner, name
	state.RepositoryHost = s.identity.forgeHost(owner, name)
	return state, err
}

// ReadmeIdentity returns the manifest identity the README governance block's badges link
// into by absolute URL (readmegovernance.State); adoption and audit both read it here. A
// manifest naming both repository.owner and repository.name returns them. Which forge hosts
// that repository is not the manifest's to say: adoption pairs the identity with the origin
// remote's host only when the remote names exactly that repository (repoIdentity.forgeHost),
// and the HISS badge stays unlinked on any host whose URL shape is unknown. Without both
// fields it returns no identity, or, under the documentation gate, whose badge needs one, an
// error wrapping errReadmeIdentityUnset.
func ReadmeIdentity(manifest *config.Manifest, documentationEnabled bool) (owner, name string, err error) {
	if manifest != nil {
		owner, name = manifest.Repository.Owner, manifest.Repository.Name
	}
	if owner != "" && name != "" {
		return owner, name, nil
	}
	if documentationEnabled {
		return "", "", errReadmeIdentityUnset
	}
	return "", "", nil
}

// errReadmeIdentityUnset: the documentation gate's badges link into the repository, and the
// manifest names none or half of one. Adoption leaves the README alone rather than link to a
// guessed repository.
var errReadmeIdentityUnset = errors.New("the documentation badges need repository.owner and repository.name")

// readmeStateError turns an unset identity into a recorded skip, so an adoption without a
// resolvable identity completes and says what it left undone; any other error fails the step.
func (s *adoptSession) readmeStateError(err error) error {
	if !errors.Is(err, errReadmeIdentityUnset) {
		return err
	}
	s.report.recordSkipped(readmeFile, "Governance block not reconciled: "+err.Error()+" in "+manifestFile+
		"; set them, or the origin remote before a first adoption, and re-run")
	return nil
}

// markdownDocument joins lines into a Markdown file ending in one newline.
//
// The scaffolded governance documents below are an adopter's own files, which the
// adopter's Markdown lint reads, so each line is written within markdownlint's default
// 80-column limit instead of opening the file with a markdownlint-disable MD013 line
// that would also silence the rule for everything the adopter adds (BUG-806).
func markdownDocument(lines ...string) string {
	return strings.Join(lines, "\n") + "\n"
}

