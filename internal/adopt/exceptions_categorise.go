package adopt

import (
	"strings"
	"time"

	"github.com/cordanaLLM/praetor/internal/config"
)

// categoriseOwnedExceptions assigns category D and an entered date to pre-category exception
// entries created by earlier Praetor adoptions (prior to engine #1711).
//
// Hand-written entries (any other rule, or a reason that does not start with the renderer
// prefix) are never modified. Expiry dates are left unchanged, so an entry exceeding its
// category limit remains refused.
//
// internal/config's lock struct (standardsLock) records no adoption date (it only stores
// version, pinned_version, digest, optional generated_at, profiles, and facets), so entered
// falls back to today (time.Now()).
func categoriseOwnedExceptions(existing []config.Exception, entered time.Time) ([]config.Exception, bool) {
	if len(existing) == 0 {
		return existing, false
	}
	result := make([]config.Exception, len(existing))
	var changed bool
	enteredDate := config.ExceptionDay(entered).Format(config.ExceptionDateLayout)
	for i := 0; i < len(existing) && i < config.MaxExceptions; i++ {
		entry := existing[i]
		if isOwnedPreCategoryException(entry) {
			entry.Category = "D"
			if entry.Entered == "" {
				entry.Entered = enteredDate
			}
			changed = true
		}
		result[i] = entry
	}
	return result, changed
}

// isOwnedPreCategoryException reports whether entry is a pre-category exception generated by
// an older Praetor adoption. It requires empty category and a reason starting with one of
// the canonical renderer prefixes (HISS-19).
func isOwnedPreCategoryException(entry config.Exception) bool {
	if entry.Category != "" {
		return false
	}
	switch entry.Rule {
	case config.ExceptionRuleDeclaredLinters:
		return strings.HasPrefix(entry.Reason, declaredLinterExceptionReasonPrefix)
	case config.ExceptionRuleSupplyChain:
		return strings.HasPrefix(entry.Reason, supplyChainExceptionReasonPrefix)
	default:
		return false
	}
}
