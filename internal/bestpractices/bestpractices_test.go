// assertCatalogLevelsAndSample asserts expected criteria levels and sample criteria rule flags.
func assertCatalogLevelsAndSample(t *testing.T, cat *Catalog) {
	t.Helper()
	for _, level := range []string{"0", "1", "2", "baseline-1", "baseline-2", "baseline-3"} {
		if len(cat.ByLevel[level]) == 0 {
			t.Fatalf("expected non-empty criteria map for level %q", level)
		}
	}
	baseCrit := cat.Criteria["osps_ac_01_01"]
	if !baseCrit.NAAllowed || !baseCrit.NAJustificationRequired || baseCrit.OriginalID != "OSPS-AC-01.01" {
		t.Fatalf("unexpected osps_ac_01_01 criterion: %+v", baseCrit)
	}
	urlCrit := cat.Criteria["contribution"]
	if urlCrit.NAAllowed || !urlCrit.MetURLRequired || urlCrit.Category != "MUST" {
		t.Fatalf("unexpected contribution criterion: %+v", urlCrit)
	}
}

