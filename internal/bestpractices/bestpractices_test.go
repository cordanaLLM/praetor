// TestValidateBytes_MultiLevelCriterionUsesLevelSpecificRules verifies that criteria spanning multiple levels apply the active level's requirements.
func TestValidateBytes_MultiLevelCriterionUsesLevelSpecificRules(t *testing.T) {
	cat, err := LoadCatalog()
	if err != nil {
		t.Fatalf("LoadCatalog() error = %v", err)
	}
	claims := []statusClaim{{criterion: "tests_documented_added", status: "Met", validString: true}}
	active := activeCriteriaForClaims(cat, claims)
	resolved := active["tests_documented_added"]
	if resolved.Level != "1" || resolved.Category != "MUST" || !resolved.MetJustificationRequired {
		t.Fatalf("resolved tests_documented_added = %+v, want level=1 category=MUST met_justification_required=true", resolved)
	}

	// tests_documented_added is SUGGESTED at level 0 (no justification required) and MUST at level 1
	// (met_justification_required: true). A claim on it alone must activate level 1 and be judged by level 1.
	rawSilver := []byte(`{
  "tests_documented_added_status": "Met"
}`)
	assertSingleFinding(t, rawSilver, "tests_documented_added", "Met", RuleMetJustificationRequired)

	// test_invocation is SHOULD at level 0 (no URL required) and MUST at level 2 (met_url_required: true).
	rawGold := []byte(`{
  "test_invocation_status": "Met",
  "test_invocation_justification": "Run make test in the repository root."
}`)
	assertSingleFinding(t, rawGold, "test_invocation", "Met", RuleMetURLRequired)
}

// TestValidateBytes_Negative_MultipleViolationsOnSingleClaim verifies that multiple rule violations on a single claim are all reported.
func TestValidateBytes_Negative_MultipleViolationsOnSingleClaim(t *testing.T) {
	// external_dependencies requires both a non-blank justification and an http(s) URL when Met.
	raw := []byte(`{
  "external_dependencies_status": "Met",
  "external_dependencies_justification": "   "
}`)
	report, err := ValidateBytes(t.Context(), raw)
	if err != nil {
		t.Fatalf("ValidateBytes() unexpected error: %v", err)
	}
	if report.Checked != 1 || len(report.Findings) != 2 {
		t.Fatalf("report = %+v, want Checked=1 and 2 findings", report)
	}
	if report.Findings[0].Rule != RuleMetJustificationRequired || report.Findings[1].Rule != RuleMetURLRequired {
		t.Fatalf("findings = %+v, want [%s, %s]", report.Findings, RuleMetJustificationRequired, RuleMetURLRequired)
	}

	naFindings := evaluateNA("custom_na", "", Criterion{NAAllowed: false, NAJustificationRequired: true})
	if len(naFindings) != 2 || naFindings[0].Rule != RuleNANotAllowed || naFindings[1].Rule != RuleNAJustificationRequired {
		t.Fatalf("evaluateNA() = %+v, want [%s, %s]", naFindings, RuleNANotAllowed, RuleNAJustificationRequired)
	}
}

// TestAudit_Boundary_AbsentPassAndFail tests Audit with absent, valid, and failing files.
func TestAudit_Boundary_AbsentPassAndFail(t *testing.T) {
	root := t.TempDir()
	line, err := Audit(t.Context(), root)
	if err != nil || !strings.HasPrefix(line, "[SKIP] bestpractices-claims:") {
		t.Fatalf("Audit(absent) = (%q, %v), want [SKIP]", line, err)
	}

	writeBestPracticesFile(t, root, `{"test_policy_status": "Unmet", "test_policy_justification": "No test policy needed for profile repo."}`)
	passLine, err := Audit(t.Context(), root)
	if err != nil || !strings.HasPrefix(passLine, "[PASS] bestpractices-claims:") {
		t.Fatalf("Audit(valid) = (%q, %v), want [PASS]", passLine, err)
	}

	writeBestPracticesFile(t, root, `{"description_good_status": "N/A", "floss_license_status": "Yes"}`)
	_, err = Audit(t.Context(), root)
	if err == nil || !strings.Contains(err.Error(), string(RuleNANotAllowed)) || !strings.Contains(err.Error(), string(RuleInvalidStatus)) {
		t.Fatalf("Audit(invalid) err = %v, want [FAIL] naming both rules", err)
	}
}

// writeBestPracticesFile writes the given content to .bestpractices.json in the test directory.
func writeBestPracticesFile(t *testing.T, root, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(root, File), []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

// assertSingleFinding verifies that validating raw JSON yields exactly one finding matching expected criterion, status, and rule.
func assertSingleFinding(t *testing.T, raw []byte, wantCriterion, wantStatus string, wantRule Rule) {
	t.Helper()
	report, err := ValidateBytes(t.Context(), raw)
	if err != nil {
		t.Fatalf("ValidateBytes() unexpected error: %v", err)
	}
	if len(report.Findings) != 1 {
		t.Fatalf("findings count = %d (%v), want 1", len(report.Findings), report.Findings)
	}
	got := report.Findings[0]
	if got.Criterion != wantCriterion || got.Status != wantStatus || got.Rule != wantRule {
		t.Fatalf("finding = %+v, want criterion=%q status=%q rule=%q", got, wantCriterion, wantStatus, wantRule)
	}
	text := got.String()
	if !strings.Contains(text, wantCriterion) || !strings.Contains(text, wantStatus) || !strings.Contains(text, string(wantRule)) {
		t.Fatalf("finding string %q missing criterion, status, or rule", text)
	}
}
