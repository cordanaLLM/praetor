// Rule identifies one OpenSSF Best Practices claim validation rule.
type Rule string

const (
	// RuleNANotAllowed refuses status N/A when na_allowed is false or absent.
	RuleNANotAllowed Rule = "na_not_allowed"
	// RuleNAJustificationRequired refuses status N/A without a non-blank justification when na_justification_required is true.
	RuleNAJustificationRequired Rule = "na_justification_required"
	// RuleMetJustificationRequired refuses status Met without a non-blank justification when met_justification_required is true.
	RuleMetJustificationRequired Rule = "met_justification_required"
	// RuleMetURLRequired refuses status Met without an http(s) URL in the justification when met_url_required is true.
	RuleMetURLRequired Rule = "met_url_required"
	// RuleInvalidStatus refuses a status outside Met, Unmet, N/A, ?.
	RuleInvalidStatus Rule = "invalid_status"
	// RuleUnknownCriterion refuses a <criterion>_status key whose criterion exists in neither YAML file.
	RuleUnknownCriterion Rule = "unknown_criterion"
)

// Criterion describes one OpenSSF Best Practices or Baseline criterion from the vendored YAML files.
type Criterion struct {
	Name                     string
	Level                    string
	MajorGroup               string
	MinorGroup               string
	Category                 string `yaml:"category"`
	Future                   bool   `yaml:"future"`
	Obsolete                 bool   `yaml:"obsolete"`
	NAAllowed                bool   `yaml:"na_allowed"`
	NAJustificationRequired  bool   `yaml:"na_justification_required"`
	MetJustificationRequired bool   `yaml:"met_justification_required"`
	MetURLRequired           bool   `yaml:"met_url_required"`
	OriginalID               string `yaml:"original_id"`
}

// BaselineMetadata holds the _metadata header from criteria/baseline_criteria.yml.
type BaselineMetadata struct {
	Source        string `yaml:"source"`
	SourceURL     string `yaml:"source_url"`
	ExtractedAt   string `yaml:"extracted_at"`
	AutoGenerated bool   `yaml:"auto_generated"`
	TotalControls int    `yaml:"total_controls"`
}

// Catalog holds the parsed criteria from both upstream YAML files.
type Catalog struct {
	Criteria map[string]Criterion
	ByLevel  map[string]map[string]Criterion
	Metadata BaselineMetadata
}

// Finding describes one invalid claim in .bestpractices.json.
type Finding struct {
	Criterion string
	Status    string
	Rule      Rule
	Detail    string
}

// String formats the finding with criterion name, status, rule identifier, and detail.
func (f Finding) String() string {
	return fmt.Sprintf("criterion %q (status %q, rule %s): %s", f.Criterion, f.Status, f.Rule, f.Detail)
}

// Report summarizes the validation of one .bestpractices.json document.
type Report struct {
	Checked  int
	Findings []Finding
}

// AssetPaths returns the repository-relative paths of the embedded upstream criteria files.
func AssetPaths() []string {
	return []string{CriteriaAssetPath, BaselineCriteriaAssetPath}
}

// Audit validates <root>/.bestpractices.json against the vendored OpenSSF Best Practices
// criteria when the file exists, or returns a stated [SKIP] line when absent.
func Audit(ctx context.Context, root string) (string, error) {
	ctx, cancel := context.WithTimeout(ctx, contextopt.MaxDuration)
	defer cancel()
	raw, exists, err := contextopt.ObserveSnapshotIn(ctx, root, File)
	if err != nil {
		return "", fmt.Errorf("[FAIL] bestpractices-claims: read %s: %w", File, err)
	}
	if !exists {
		return "[SKIP] bestpractices-claims: no .bestpractices.json found; not applicable.", nil
	}
	report, err := ValidateBytes(ctx, raw)
	if err != nil {
		return "", fmt.Errorf("[FAIL] bestpractices-claims: %w", err)
	}
	if len(report.Findings) > 0 {
		return "", fmt.Errorf("[FAIL] bestpractices-claims: %s has %d forbidden claim(s): %s",
			File, len(report.Findings), formatFindings(report.Findings))
	}
	return fmt.Sprintf("[PASS] bestpractices-claims: %s verified (%d criterion claim(s) checked against OpenSSF Best Practices criteria@%s).",
		File, report.Checked, SourceCommit), nil
}

// ValidateBytes parses a .bestpractices.json payload and checks every <criterion>_status claim
// against the vendored OpenSSF Best Practices and Baseline criteria.
func ValidateBytes(ctx context.Context, raw []byte) (*Report, error) {
	ctx, cancel := context.WithTimeout(ctx, contextopt.MaxDuration)
	defer cancel()
	if err := clientjson.Validate(ctx, raw); err != nil {
		return nil, fmt.Errorf("parse %s: %w", File, err)
	}
	object, err := clientjson.DecodeObject(raw)
	if err != nil {
		return nil, fmt.Errorf("decode %s: %w", File, err)
	}
	cat, err := LoadCatalog()
	if err != nil {
		return nil, fmt.Errorf("load criteria catalog: %w", err)
	}
	claims, justifications, err := extractClaims(object)
	if err != nil {
		return nil, err
	}
	criteria := activeCriteriaForClaims(cat, claims)
	report := &Report{Checked: len(claims)}
	for i := 0; i < len(claims) && i < maxObjectMembers; i++ {
		claim := claims[i]
		report.Findings = append(report.Findings, evaluateClaim(claim, justifications[claim.criterion], criteria)...)
	}
	return report, nil
}

// formatFindings formats a slice of findings into a semicolon-separated string.
func formatFindings(findings []Finding) string {
	parts := make([]string, 0, len(findings))
	for i := 0; i < len(findings) && i < maxObjectMembers*2; i++ {
		parts = append(parts, findings[i].String())
	}
	return strings.Join(parts, "; ")
}
