package util

import "encoding/hex"

// ValidGitObjectID reports whether value is a 40- or 64-character hexadecimal Git object ID
// (SHA-1 or SHA-256 repositories).
func ValidGitObjectID(value string) bool {
	if len(value) != 40 && len(value) != 64 {
		return false
	}
	_, err := hex.DecodeString(value)
	return err == nil
}
