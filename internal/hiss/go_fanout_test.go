func TestGoFanout_Negative_AcceptedBoundsPass(t *testing.T) {
	for _, tc := range acceptedFanoutBounds {
		t.Run(tc.name, func(t *testing.T) {
			rep := scanGoSnippet(tc.src, tc.name+".go")
			if got := rep.Breakdown["HISS-06"]; got != 0 {
				t.Fatalf("Breakdown[HISS-06] = %d, want 0; violations=%+v", got, rep.Violations)
			}
		})
	}
}

func TestGoFanout_Boundary_EmptyAndParseErrorFiles(t *testing.T) {
	emptyRep := scanGoSnippet("", "empty.go")
	if emptyRep.Skips.Unparsed != 1 || !emptyRep.Incomplete() {
		t.Fatalf("empty file must record Unparsed=1 and Incomplete()=true (error not skip), got skips=%+v", emptyRep.Skips)
	}
	if len(emptyRep.Violations) != 0 {
		t.Fatalf("empty file should not produce violations, got %+v", emptyRep.Violations)
	}

	brokenSrc := "package p\nfunc Broken(items []string) {\n\tfor _, item := range items {\n\t\tgo work(item)\n\t}\n\tif {\n}\n"
	brokenRep := scanGoSnippet(brokenSrc, "broken.go")
	if brokenRep.Skips.Unparsed != 1 || !brokenRep.Incomplete() {
		t.Fatalf("parse error file must record Unparsed=1 and Incomplete()=true, got skips=%+v", brokenRep.Skips)
	}
	if got := brokenRep.Breakdown["HISS-06"]; got != 1 {
		t.Fatalf("partial AST before syntax error should still report HISS-06=1, got %d", got)
	}
}

func TestGoFanout_Boundary_OwnComplexityWithinHISS04(t *testing.T) {
	path := filepath.Join("go_fanout.go")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, data, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	for _, unit := range MeasureFile(fset, file) {
		if unit.Metrics.LOC > DefaultMaxFuncLOC {
			t.Errorf("%s LOC = %d > %d", unit.Name, unit.Metrics.LOC, DefaultMaxFuncLOC)
		}
		if unit.Metrics.Cyclomatic > DefaultMaxCyclomatic {
			t.Errorf("%s Cyclomatic = %d > %d", unit.Name, unit.Metrics.Cyclomatic, DefaultMaxCyclomatic)
		}
		if unit.Metrics.Cognitive > DefaultMaxCognitive {
			t.Errorf("%s Cognitive = %d > %d", unit.Name, unit.Metrics.Cognitive, DefaultMaxCognitive)
		}
		if unit.Metrics.Statements > DefaultMaxStatements {
			t.Errorf("%s Statements = %d > %d", unit.Name, unit.Metrics.Statements, DefaultMaxStatements)
		}
	}
}

func assertFanoutFinding(t *testing.T, src, rel string, line int, fn string) {
	t.Helper()
	rep := scanGoSnippet(src, rel)
	if got := rep.Breakdown["HISS-06"]; got != 1 {
		t.Fatalf("Breakdown[HISS-06] = %d, want 1; violations=%+v", got, rep.Violations)
	}
	var found *InvariantViolation
	for i := 0; i < len(rep.Violations); i++ {
		if rep.Violations[i].RuleID == "HISS-06" {
			found = &rep.Violations[i]
			break
		}
	}
	if found == nil {
		t.Fatalf("missing HISS-06 violation in %+v", rep.Violations)
	}
	if found.LineNumber != line {
		t.Errorf("line = %d, want %d", found.LineNumber, line)
	}
	if found.Symbol != fn {
		t.Errorf("symbol = %q, want %q", found.Symbol, fn)
	}
	for _, needle := range []string{fn, "errgroup.Group.SetLimit", "semaphore.Weighted.Acquire",
		"buffered token channel", "constant/array loop bound", "//hiss:bound"} {
		if !strings.Contains(found.Message, needle) {
			t.Errorf("message %q missing %q", found.Message, needle)
		}
	}
}
