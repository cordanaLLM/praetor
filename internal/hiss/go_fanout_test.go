func scanGoSnippet(src, rel string) *ScanReport {
	rep := &ScanReport{
		Breakdown: make(map[string]int),
	}
	scanGoSource([]byte(src), rel, rep, ScanOptions{MaxFuncLOC: DefaultMaxFuncLOC})
	return rep
}

