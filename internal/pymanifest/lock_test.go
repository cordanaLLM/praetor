const lockFixture = `# This file was autogenerated by uv via the following command:
#    uv pip compile --universal --generate-hashes --python-version=3.11 requirements.in --output-file=requirements.txt
markdown==3.10.3 ; python_full_version < '3.12' \
    --hash=sha256:aaaa
    # via mkdocs
markdown==3.11 ; python_full_version >= '3.12' \
    --hash=sha256:bbbb
mkdocs-material==9.8.0 \
    --hash=sha256:cccc
    # via -r requirements.in
`

// Positive: every exact pin the lock holds, spelled with other separators or case, with extras
// and a comment, or held under one of several marker-split versions, is no finding.
func TestUnlockedPins_Positive_HeldPinsPass(t *testing.T) {
	if got := UnlockedPins("Mkdocs_Material[imaging]==9.8.0  # theme\nmarkdown==3.11\n", lockFixture); len(got) != 0 {
		t.Fatalf("UnlockedPins = %q, want none", got)
	}
}

// Negative (#1697): a pin the lock holds at another version, or not at all, is named in the
// order requirements.in lists it.
func TestUnlockedPins_Negative_DriftNamed(t *testing.T) {
	if got, want := UnlockedPins("mkdocs-material==9.8.1\nmkdocs==1.6.1\nmarkdown==3.11\n", lockFixture), []string{"mkdocs-material==9.8.1", "mkdocs==1.6.1"}; !slices.Equal(got, want) {
		t.Fatalf("UnlockedPins = %q, want %q", got, want)
	}
}

// Boundary: ranges, arbitrary equality, bare names, options, comments and a hash line carry no
// exact pin, so they are not compared, and an empty lock holds nothing.
func TestUnlockedPins_Boundary_OnlyExactPinsCompared(t *testing.T) {
	if got := UnlockedPins("mkdocs>=1.6\nmkdocs-material===9.8.0\npymdown-extensions\n-r base.in\n# mkdocs==9\n--hash=sha256:dddd\n", lockFixture); len(got) != 0 {
		t.Fatalf("UnlockedPins = %q, want none", got)
	}
	if got := UnlockedPins("mkdocs==1.6.1\n", ""); !slices.Equal(got, []string{"mkdocs==1.6.1"}) {
		t.Fatalf("empty lock: UnlockedPins = %q", got)
	}
}

// TestNormalizeName covers PEP 503 folding: case and every run of "-", "_" and ".".
func TestNormalizeName(t *testing.T) {
	for in, want := range map[string]string{
		"Typing_Extensions": "typing-extensions", "zope.interface": "zope-interface",
		"a-_.b": "a-b", "plain": "plain", "trailing_": "trailing-",
	} {
		if got := NormalizeName(in); got != want {
			t.Errorf("NormalizeName(%q) = %q, want %q", in, got, want)
		}
	}
}

// maxManifestWalk bounds the repository walk for requirements.in files.
const maxManifestWalk = 200_000

// Every tracked requirements.in in this repository has its pins in the lock beside it, so an
// edit to the input that skipped the recompile fails here instead of shipping (#1697).
func TestTrackedRequirementLocksHoldTheirPins(t *testing.T) {
	root := filepath.Join("..", "..")
	visited, checked := 0, 0
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		visited++
		if visited > maxManifestWalk {
			return filepath.SkipAll
		}
		if entry.IsDir() && slices.Contains([]string{".git", "node_modules", ".workingdir", ".claude", ".standards", "testdata"}, entry.Name()) {
			return filepath.SkipDir
		}
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), "requirements") || filepath.Ext(entry.Name()) != ".in" {
			return nil
		}
		checked++
		assertLockHoldsPins(t, path, strings.TrimSuffix(path, ".in")+".txt")
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if checked == 0 {
		t.Fatal("no requirements.in found; the walk no longer reaches the repository's locks")
	}
}

func assertLockHoldsPins(t *testing.T, inPath, lockPath string) {
	t.Helper()
	in, err := os.ReadFile(inPath)
	if err != nil {
		t.Fatal(err)
	}
	lock, err := os.ReadFile(lockPath)
	if err != nil {
		t.Errorf("%s has no lock %s: %v", inPath, lockPath, err)
		return
	}
	if missing := UnlockedPins(string(in), string(lock)); len(missing) != 0 {
		t.Errorf("%s pins %s, which %s does not hold; recompile the lock with the command in its header", inPath, strings.Join(missing, ", "), lockPath)
	}
}
