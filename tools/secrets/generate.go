package secrets

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/cordanaLLM/praetor/internal/util"
)

// maxRulesSourceBytes bounds the rules source the generator reads (HISS-02).
const maxRulesSourceBytes = 4 << 20

const (
	// RulesSourcePath is the repository-relative path to the rules source file.
	RulesSourcePath = "tools/secrets/rules/rules.go"
	// RulesGenDestPath is the repository-relative path to the generated gate rules file.
	RulesGenDestPath = "tools/secrets/gate/rules_gen.go"
	// GeneratedHeader marks the generated rules code.
	GeneratedHeader = "// Code generated by tools/secrets/generate.go; DO NOT EDIT.\n\n"
)

// GenerateRulesGen takes the content of rules.go and produces the gate/rules_gen.go source.
func GenerateRulesGen(source []byte) ([]byte, error) {
	s := string(source)
	idx := strings.Index(s, "package rules")
	if idx < 0 {
		return nil, fmt.Errorf("package rules declaration not found in source")
	}
	header := s[:idx]
	body := s[idx+len("package rules"):]

	var buf bytes.Buffer
	buf.WriteString("//go:build " + BuildTag + "\n\n")
	buf.WriteString(header)
	buf.WriteString(GeneratedHeader)
	buf.WriteString("package main")
	buf.WriteString(body)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated rules: %w", err)
	}
	return formatted, nil
}

// WriteRulesGen reads rules.go from repoRoot, generates rules_gen.go, and writes it.
func WriteRulesGen(repoRoot string) error {
	srcPath := filepath.Join(repoRoot, RulesSourcePath)
	data, err := util.ReadFileLimited(srcPath, maxRulesSourceBytes)
	if err != nil {
		return fmt.Errorf("read %s: %w", srcPath, err)
	}
	gen, err := GenerateRulesGen(data)
	if err != nil {
		return err
	}
	destPath := filepath.Join(repoRoot, RulesGenDestPath)
	return os.WriteFile(destPath, gen, 0o600)
}
